public class HolaMundo {
public static void main(String[] args) {
    String nombre = "Osacar";
    int edad = 20;
    double altura = 1.70;
    System.out.println("Nombre: " + nombre);
    System.out.println("Edad: " + edad);
    System.out.println("Altura: " + altura);
    int suma = edad + 5;
    System.out.println("Edad + 5: " + suma);
    int resta = edad - 5;
    System.out.println("Edad - 5: " + resta);
    int multiplicacion = edad * 2;
    System.out.println("Edad * 2: " + multiplicacion);
    double division = altura / 2;
    System.out.println("Altura / 2: " + division);
    int modulo = edad % 3;
    System.out.println("Edad % 3: " + modulo);
}
}